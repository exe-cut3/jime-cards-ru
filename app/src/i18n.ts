export const DICT: Record<Lang, Dict> = { ru, en };

export const LangContext = createContext<Lang>('ru');

export function useI18n(): { lang: Lang; t: Dict } {
  const lang = useContext(LangContext);
  return { lang, t: DICT[lang] };
}

// ---- language choice: URL ?lang= → saved choice → browser language
const LANG_KEY = 'jime.lang';

export function detectLang(search = window.location.search): Lang {
  const p = new URLSearchParams(search).get('lang');
  if (p === 'ru' || p === 'en') return p;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  return langs.some((l) => /^(ru|uk|be|kk)\b/i.test(l ?? '')) ? 'ru' : 'en';
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* ignore */
  }
}
